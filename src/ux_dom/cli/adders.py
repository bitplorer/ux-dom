"""``uxdom add`` — generate routes, components, and XElements in an app tree."""

from __future__ import annotations

import re
from pathlib import Path
from typing import Literal, Optional


class AddError(RuntimeError):
    pass


def _ensure_route_packages(routes_root: Path, file_path: Path) -> None:
    """Create ``__init__.py`` for every package dir from routes_root → file parent."""
    routes_root = routes_root.resolve()
    parent = file_path.parent.resolve()
    try:
        rel = parent.relative_to(routes_root)
    except ValueError:
        return
    cur = routes_root
    for part in rel.parts:
        cur = cur / part
        init = cur / "__init__.py"
        if not init.exists():
            init.write_text("", encoding="utf-8")


def _find_app_root(start: Optional[Path] = None) -> Path:
    cur = (start or Path.cwd()).resolve()
    for p in [cur, *cur.parents]:
        if (p / "app" / "routes").is_dir() and (p / "app").is_dir():
            return p
        if p == p.parent:
            break
    raise AddError(
        "not inside a ux-dom app (expected app/routes/). "
        "Run from a project with app/routes/. Product page units: uxcompose create-app."
    )


def _class_name(name: str) -> str:
    parts = re.split(r"[^a-zA-Z0-9]+", name.strip())
    parts = [p for p in parts if p]
    if not parts:
        raise AddError("empty name")
    return "".join(p[:1].upper() + p[1:] for p in parts)


def _path_params_from_route_name(name: str) -> list[str]:
    """Extract ``[id]`` → id from a route path string."""
    return re.findall(r"\[([a-zA-Z_][a-zA-Z0-9_]*)\]", name)


def _module_stem(name: str) -> str:
    s = re.sub(r"[^a-zA-Z0-9_]+", "_", name.strip()).strip("_").lower()
    if not s:
        raise AddError("empty name")
    if s[0].isdigit():
        s = "r_" + s
    return s


def add_component(
    name: str, *, root: Optional[Path] = None, force: bool = False
) -> Path:
    """Create ``app/components/{stem}.py`` with a Component stub."""
    app_root = _find_app_root(root)
    stem = _module_stem(name)
    cls = _class_name(name)
    path = app_root / "app" / "components" / f"{stem}.py"
    if path.exists() and not force:
        raise AddError(f"{path} exists (use --force)")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f'''"""{cls} component — generated by ``uxdom add component``."""
from __future__ import annotations

from ux_dom import Component
from ux_dom.dom import div


class {cls}(Component):
    def render(self, *args, **kwargs):
        return div("{cls}", className="p-4")
'''
        ,
        encoding="utf-8",
    )
    return path


_VERBS = ("get", "post", "put", "patch", "delete")


def _parse_methods(methods: str) -> list[str]:
    verbs = [m.strip().lower() for m in (methods or "get").split(",") if m.strip()]
    bad = [m for m in verbs if m not in _VERBS]
    if bad:
        raise AddError(f"unknown HTTP method(s) {bad}; use {', '.join(_VERBS)}")
    if "get" not in verbs:
        verbs.insert(0, "get")
    return list(dict.fromkeys(verbs))


def add_route(
    name: str,
    *,
    root: Optional[Path] = None,
    force: bool = False,
    page_title: Optional[str] = None,
    methods: str = "get",
) -> Path:
    """Create a page under ``app/routes/`` that follows the DirectoryRouter law.

    The URL is the file path; the class is never part of it.

    * ``about``             -> ``about.py``, class ``About``, GET /about
    * ``my-page``           -> ``my_page.py``, class ``MyPage``, GET /my_page
    * ``admin/dashboard``   -> ``admin/dashboard.py``, GET /admin/dashboard
    * ``users/[id]``        -> ``users/[id]/route.py``, ``get(id: str)``,
      GET /users/{id}
    * ``index``             -> ``index.py``, class ``Index``, GET /

    ``methods`` is a comma list (``get,post``); ``get`` is always included.
    """
    app_root = _find_app_root(root)
    verbs = _parse_methods(methods)
    segs = [s for s in name.strip().strip("/").split("/") if s]
    if not segs:
        raise AddError("empty name")
    parts = []
    for seg in segs:
        m = re.fullmatch(r"\[([a-zA-Z_][a-zA-Z0-9_]*)\]", seg)
        parts.append(seg if m else (_module_stem(seg) if seg != "index" else "index"))
    params = _path_params_from_route_name("/".join(parts))
    title = page_title
    if parts[-1].startswith("["):
        # Path-param leaf: route.py maps to its folder, verbs are functions.
        rel = Path(*parts) / "route.py"
        sig = ", ".join(f"{p}: str" for p in params)
        shown = " / ".join(f"{{{p}}}" for p in params)
        title_src = repr(title) if title else "f\"" + shown + "\""
        body = "".join(
            f'''

def {verb}({sig}):
    return page(_view({", ".join(params)}), page_title={title_src})
'''
            for verb in verbs
        )
        content = f'''"""{"/".join(parts)} — generated by ``uxdom add route``."""
from __future__ import annotations

from ux_dom.dom import a, div, h1, p

from app.document import page


def _view({sig}):
    return div(
        a("← Home", href="/", className="text-sm text-sky-600"),
        h1(f"{shown}", className="text-2xl font-bold mt-4 mb-2"),
        p("Edit this file under app/routes/.", className="text-slate-600"),
        className="max-w-2xl mx-auto px-4 py-10",
    )
{body}'''
    else:
        stem = parts[-1]
        rel = Path(*parts[:-1], f"{stem}.py")
        cls = "Index" if stem == "index" else _class_name(stem)
        sig = "".join(f", {p}: str" for p in params)
        title_src = repr(title or cls)
        extra = "".join(
            f'''

    @classmethod
    def {verb}(cls{sig}):
        return cls()
'''
            for verb in verbs
            if verb != "get"
        )
        content = f'''"""{cls} page — generated by ``uxdom add route``."""
from __future__ import annotations

from ux_dom import Component
from ux_dom.dom import a, div, h1, p

from app.document import page

__all__ = ["{cls}"]


class {cls}(Component):
    routes = [{", ".join(f'"{v}"' for v in verbs)}]

    def render(self, *args, **kwargs):
        return div(
            a("← Home", href="/", className="text-sm text-sky-600"),
            h1("{cls}", className="text-2xl font-bold mt-4 mb-2"),
            p("Edit this file under app/routes/.", className="text-slate-600"),
            className="max-w-2xl mx-auto px-4 py-10",
        )

    @classmethod
    def get(cls{sig}):
        # Path params arrive by name (never **kwargs).
        return page(cls(), page_title={title_src})
{extra}'''

    path = app_root / "app" / "routes" / rel
    if path.exists() and not force:
        raise AddError(f"{path} exists (use --force)")
    path.parent.mkdir(parents=True, exist_ok=True)
    _ensure_route_packages(app_root / "app" / "routes", path)
    path.write_text(content, encoding="utf-8")
    return path


XKind = Literal["light", "shadow", "alpine"]


def add_xelement(
    name: str,
    *,
    kind: XKind = "light",
    root: Optional[Path] = None,
    force: bool = False,
) -> Path:
    """Create an XElement subclass under app/components/."""
    if not name or not str(name).strip():
        raise AddError("empty name")
    app_root = _find_app_root(root)
    stem = _module_stem(name)
    cls = _class_name(name)
    path = app_root / "app" / "components" / f"{stem}.py"
    if path.exists() and not force:
        raise AddError(f"{path} exists (use --force)")
    path.parent.mkdir(parents=True, exist_ok=True)

    # Stubs follow the htmlelement contract: ``{cls}()`` places the host,
    # ``render`` returns the definition template carrying ``x-tagname``.
    tag = stem.replace("_", "-")
    if kind == "light":
        body = f'''"""{cls} XElement (light) — generated by ``uxdom add xelement``."""
from __future__ import annotations

from ux_dom.dom import div, template
from ux_dom.dom.htmlelement import CustomElement


class {cls}(CustomElement):
    tag_name = "{tag}"

    def render(self, tag_name: str = "{tag}"):
        return template(
            div(f"{cls} light", className="p-2 border rounded"),
            **{{"x-tagname": tag_name}},
        )
'''
    elif kind == "shadow":
        body = f'''"""{cls} XElement (shadow) — generated by ``uxdom add xelement``."""
from __future__ import annotations

from ux_dom.dom import div, slot, template
from ux_dom.dom.htmlelement import WebComponent


class {cls}(WebComponent):
    tag_name = "{tag}"

    def render(self, tag_name: str = "{tag}"):
        return template(
            div(f"{cls} shadow", slot(), className="p-2 border rounded"),
            **{{"x-tagname": tag_name, "shadowroot": "true"}},
        )
'''
    else:  # alpine
        body = f'''"""{cls} XElement (alpine) — generated by ``uxdom add xelement``."""
from __future__ import annotations

from ux_dom.dom import div, template
from ux_dom.dom.htmlelement import AlpineComponent


class {cls}(AlpineComponent):
    tag_name = "{tag}"

    def render(self, tag_name: str = "{tag}"):
        return template(
            div(
                f"{cls} alpine",
                **{{"x-data": "{{ open: false }}"}},
                className="p-2 border rounded",
            ),
            **{{"x-tagname": tag_name}},
        )
'''
    path.write_text(body, encoding="utf-8")
    return path
